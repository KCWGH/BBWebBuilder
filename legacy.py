"""JDP and RAPC manifest helpers adapted from the existing Windows builder."""
import os
import re

SOURCE_EXT = {".java"}
RESOURCE_EXT = {
    ".png", ".gif", ".jpg", ".jpeg", ".bmp", ".dat", ".txt", ".xml",
    ".ogg", ".mp3", ".wav", ".amr", ".mid", ".midi", ".json", ".csv",
    ".properties", ".res", ".cmap", ".otf", ".ttf",
}
EXCLUDE_EXT = {
    ".cod", ".cso", ".debug", ".jad", ".jar", ".rapc", ".class",
    ".jdp", ".jdw", ".pyc", ".alx", ".log",
}
EXCLUDE_DIRS = {".git", "__pycache__", ".metadata", ".settings", "deliverables", ".venv", "venv", "node_modules"}
# rapc 실측 한도: 아이콘 파일이 16384(=16KB) 바이트를 넘으면 "Error!907: Icon data
# is too large" 로 빌드 실패한다. 16384 까지 통과, 16385 부터 실패.
ICON_MAX_BYTES = 16384


def is_buildable(filename):
    return os.path.splitext(filename)[1].lower() in (SOURCE_EXT | RESOURCE_EXT)


def safe_name(s):
    """앱 이름을 폴더/파일명으로 쓸 수 있게 정리."""
    s = (s or "App").strip()
    s = re.sub(r'[<>:"/\\|?*]', "_", s)
    return s or "App"


def icon_size_error(path):
    """아이콘 png 크기 제한 검사. 문제 없으면 None, 초과/오류면 안내 메시지 반환.
    아이콘이 너무 크면 rapc 가 'Error!907: Icon data is too large' 로 빌드 실패한다."""
    try:
        size = os.path.getsize(path)
    except OSError:
        return "파일을 읽을 수 없습니다."
    if size > ICON_MAX_BYTES:
        return (f"아이콘 파일이 너무 큽니다.\n\n"
                f"선택한 파일: {size:,} bytes\n"
                f"허용 한도: {ICON_MAX_BYTES:,} bytes 이하\n\n"
                f"아이콘이 너무 크면 빌드가 실패합니다(Error!907).\n"
                f"더 작은 png(예: 80×80 내외)를 사용하세요.")
    return None


