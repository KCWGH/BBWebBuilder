def find_midlet_class(project_dir, files):
    """소스 중 javax.microedition.midlet.MIDlet 을 상속하는 클래스를 찾는다.
    발견하면 (package 포함) 완전한 클래스 이름을 반환 → MIDlet 앱으로 빌드.
    없으면 "" 반환 → 기존과 동일하게 main(String[]) 진입점의 CLDC 앱으로 빌드."""
    for rel in files:
        if not rel.lower().endswith(".java"):
            continue
        path = os.path.join(project_dir, rel)
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                text = f.read()
        except OSError:
            continue
        m = re.search(r'class\s+(\w+)\s+extends\s+(?:javax\.microedition\.midlet\.)?MIDlet\b', text)
        if not m:
            continue
        cls = m.group(1)
        pkg = re.search(r'^\s*package\s+([\w.]+)\s*;', text, re.M)
        return (pkg.group(1) + "." + cls) if pkg else cls
    return ""


def write_rapc_manifest(manifest_path, info, jar_name, midlet_class=""):
    name = info.get("OutputFileName") or info.get("Title") or "App"
    title = info.get("Title", "")
    icon = info["icons"][0].replace("\\", "/") if info["icons"] else ""
    vendor = info.get("Vendor") or "<unknown>"
    version = info.get("Version") or "0.0"
    lines = [
        f"MIDlet-Name: {name}",
        f"MIDlet-Version: {version}",
        f"MIDlet-Vendor: {vendor}",
        f"MIDlet-Jar-URL: {jar_name}",
        "MIDlet-Jar-Size: 0",
        "MicroEdition-Profile: MIDP-2.0",
        "MicroEdition-Configuration: CLDC-1.1",
        # 세 번째 필드가 비어 있으면 rapc 는 main() 진입점의 CLDC 앱으로 취급하고,
        # MIDlet 클래스 이름이 있으면 MIDlet 으로 빌드한다.
        f"MIDlet-1: {title},{icon},{midlet_class}",
        "RIM-MIDlet-Flags-1: 0",
        "",
    ]
    with open(manifest_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


