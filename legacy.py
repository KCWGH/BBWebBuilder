def parse_jdp(jdp_path):
    info = {
        "files": [], "icons": [],
        "OutputFileName": "", "Title": "", "Vendor": "<unknown>", "Version": "0.0",
    }
    list_sections = {"[Files": "files", "[Icons": "icons"}
    current_list = None
    with open(jdp_path, "r", encoding="utf-8-sig") as f:
        for line in f:
            clean = line.strip()
            if not clean:
                continue
            if clean == "]":
                current_list = None
                continue
            if clean.startswith("["):
                current_list = None
                for prefix, key in list_sections.items():
                    if clean.startswith(prefix):
                        current_list = key
                        break
                continue
            if current_list:
                if "." in clean:
                    info[current_list].append(clean.replace("\\", "/"))
                continue
            if "=" in clean:
                key, _, value = clean.partition("=")
                key = key.strip()
                if key in info:
                    info[key] = value.strip()
    return info


def scan_project(project_dir):
    sources, resources, root_pngs = [], [], []
    for dirpath, dirnames, filenames in os.walk(project_dir):
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
        for fn in sorted(filenames):
            ext = os.path.splitext(fn)[1].lower()
            if ext in EXCLUDE_EXT:
                continue
            abs_fp = os.path.join(dirpath, fn)
            rel = os.path.relpath(abs_fp, project_dir).replace("\\", "/")
            if ext in SOURCE_EXT:
                sources.append(rel)
            elif ext in RESOURCE_EXT:
                resources.append(rel)
                if (ext == ".png" and dirpath == project_dir
                        and os.path.getsize(abs_fp) <= ICON_MAX_BYTES):
                    root_pngs.append(rel)
    icon = ""
    pname = os.path.basename(os.path.normpath(project_dir)).lower()
    for cand in root_pngs:
        if os.path.splitext(cand)[0].lower() in ("icon", pname):
            icon = cand
            break
    if not icon and root_pngs:
        icon = root_pngs[0]
    return {"sources": sources, "resources": resources, "icon": icon}


